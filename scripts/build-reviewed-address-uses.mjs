// Deterministic, explicitly approved card evidence. Does not modify map geometry,
// the legacy currentUse pipeline, holds, or historical classifications.
import fs from 'node:fs'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { findCurrentUseHold } from './lib/current-use-holds.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const read = p => fs.readFileSync(root + p, 'utf8')
const json = p => JSON.parse(read(p))
const sha = text => createHash('sha256').update(text).digest('hex')
const approval = json('scripts/data/french-concession-address-use-approvals.json')
const text = read(approval.lookupPath)
assert.equal(sha(text), approval.lookupSha256, 'Research changed: review the display approval again')
const lookup = JSON.parse(text)
assert.equal(sha(read(lookup.sourcePath)), lookup.sourceSha256)
assert.equal(sha(read(lookup.roadAuditPath)), lookup.roadAuditSha256)
const approved = new Set(approval.approvedSourceIds)
assert.equal(approved.size, approval.approvedSourceIds.length)
assert.equal(approved.size, 64)
const strong = new Map(approval.confirmedIdentity.map(r => [r.sourceId, r.reason]))
assert.equal(strong.size, approval.confirmedIdentity.length)
assert([...strong].every(([id, reason]) => approved.has(id) && reason))
const sources = new Map(lookup.sources.map(s => [s.id, s]))
assert.equal(sources.size, lookup.sources.length)
const byId = new Map()
for (const result of lookup.records) for (const id of result.sourceIds) {
  assert(!byId.has(id), `Duplicate research ID ${id}`)
  byId.set(id, result)
}
const features = json('public/data/historical-features.geojson').features
const holds = json('scripts/data/landmark-current-use-holds.json')
const entries = []
const applied = new Set()
for (const feature of features) {
  const p = feature.properties
  const ids = p.sourceRecordIds ?? []
  if (p.kind !== 'landmark' || !ids.some(id => approved.has(id))) continue
  assert(ids.every(id => approved.has(id)), `Mixed approved/unapproved group ${p.id}`)
  assert(!p.currentUse, `Existing currentUse requires separate conflict review: ${p.id}`)
  const hold = findCurrentUseHold(holds, p)
  const decisions = [...new Set(ids.map(id => byId.get(id)))]
  const evidence = decisions.map(result => {
    assert(result?.status === 'address-use-supported', `Not supported: ${p.id}`)
    assert(result.modernUse && result.matchedModernAddress && result.identityNote)
    const memberIds = result.sourceIds.filter(id => ids.includes(id))
    for (const id of memberIds) {
      assert(!applied.has(id), `Duplicate display target ${id}`)
      applied.add(id)
    }
    const confirmed = memberIds.every(id => strong.has(id))
    assert(!confirmed || !hold, `Cannot promote a held group: ${p.id}`)
    const references = result.sourceRefs.map(id => {
      const source = sources.get(id)
      assert(source, `Missing source ${id}`)
      assert(['https:', 'http:'].includes(new URL(source.url).protocol))
      assert(source.title && source.supports && source.accessedOn)
      return { ...source }
    })
    assert(references.length)
    return {
      sourceRecordIds: memberIds,
      mode: confirmed ? 'current-use' : 'address-reference',
      use: result.modernUse,
      address: result.matchedModernAddress,
      note: result.identityNote,
      ...(confirmed ? { identityBasis: memberIds.map(id => strong.get(id)).join('；') } : {}),
      ...(hold ? { retainedHold: { reason: hold.reason, reviewRef: hold.reviewRef } } : {}),
      reviewedOn: result.reviewedOn,
      sources: references,
    }
  })
  entries.push({ featureId: p.id, expectedSourceRecordIds: ids, evidence })
}
assert.deepEqual([...applied].sort((a,b) => a-b), [...approved].sort((a,b) => a-b))
entries.sort((a,b) => Math.min(...a.expectedSourceRecordIds) - Math.min(...b.expectedSourceRecordIds))
const output = '// Generated by scripts/build-reviewed-address-uses.mjs; do not edit.\n'
  + "import type { ReviewedAddressUse } from '../lib/reviewedAddressUses'\n\n"
  + `export const reviewedAddressUses: ReviewedAddressUse[] = ${JSON.stringify(entries, null, 2)}\n`
const target = root + 'src/data/reviewedAddressUses.ts'
if (process.argv.includes('--write')) fs.writeFileSync(target, output)
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), output)
console.log(JSON.stringify({ sourceRecords: applied.size, mapFeatures: entries.length,
  currentUseRecords: strong.size, referenceRecords: approved.size - strong.size,
  retainedHoldRecords: entries.flatMap(e => e.evidence).filter(e => e.retainedHold).flatMap(e => e.sourceRecordIds).length }, null, 2))
